-- ============================================================
-- 운영진 비밀번호 설정. 이 파일만 따로 실행
-- ------------------------------------------------------------
-- 언제 실행하나요?
--   설치(setup_all.sql)를 마친 직후 한 번
--   비밀번호를 바꾸고 싶을 때
--   운영진이 바뀌었을 때 (이전 운영진의 접근을 끊으려면 반드시)
--
-- 설치 파일은 비밀번호를 건드리지 않습니다. 설치 파일을 다시 Run 해도
-- 여기서 정한 비밀번호는 그대로입니다.
--
-- 하는 법
--   1. 아래 'p text :=' 줄의 '여기에_새_비밀번호' 만 새 비밀번호로 바꿉니다.
--      (작은따옴표 ' 는 그대로 두고 글자만 교체. 비밀번호 안에 ' 는 쓰지 않습니다)
--   2. Run. 결과가 '설정됨' 한 줄이면 끝입니다.
--   3. SQL Editor 의 내용을 지우고, 저장된 쿼리(snippet)로 남았으면 그것도 지웁니다.
--
-- 바꾸지 않았거나 10자보다 짧으면 아무것도 바꾸지 않고 멈춥니다.
-- (예전에는 이 파일을 그대로 Run 하면 비밀번호가 '여기에_새_비밀번호' 로 정해졌다)
--
-- 주의: 이 파일을 비밀번호가 적힌 채로 저장하거나 커밋하지 마세요.
-- ============================================================

do $$
declare
  p text := '여기에_새_비밀번호';
begin
  if p like '여기에%' then
    raise exception '비밀번호를 바꾸지 않았습니다. 따옴표 안 글자를 새 비밀번호로 바꾸고 다시 Run 하세요.';
  end if;
  if length(p) < 10 then
    raise exception '비밀번호가 너무 짧습니다. 10자 이상으로 정해 주세요.';
  end if;
  insert into site_config (key, value)
  values ('admin_pass_hash', site_hash(p))
  on conflict (key) do update set value = excluded.value;
end $$;

-- 확인: 비밀번호를 다시 적지 않고 저장 상태만 봅니다.
select case when value <> 'UNSET' and length(value) = 64 then '설정됨' else '설정 안 됨' end as 운영진_비밀번호
from site_config where key = 'admin_pass_hash';
