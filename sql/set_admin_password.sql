-- ============================================================
-- 운영진 비밀번호 설정 — 이 파일만 따로 실행
-- ------------------------------------------------------------
-- 언제 실행하나요?
--   · 설치(setup_all.sql)를 마친 직후 한 번
--   · 비밀번호를 바꾸고 싶을 때
--   · 운영진이 바뀌었을 때 (이전 운영진의 접근을 끊으려면 반드시)
--
-- 설치 파일은 이제 비밀번호를 건드리지 않습니다. 그래서 이 절차가 필요합니다.
-- 반대로 말하면, 설치 파일을 몇 번을 다시 Run 해도 여기서 정한 비밀번호는 그대로입니다.
--
-- ★ 아래 한 줄의 '여기에_새_비밀번호' 만 바꾸고 Run 하세요.
--   (작은따옴표 ' 는 그대로 두고 글자만 교체)
--
-- 주의: 이 파일을 비밀번호가 적힌 채로 저장하거나 커밋하지 마세요.
--       Run 한 뒤에는 SQL Editor 의 내용을 지워 주세요.
-- ============================================================

insert into site_config (key, value)
values ('admin_pass_hash', site_hash('여기에_새_비밀번호'))
on conflict (key) do update set value = excluded.value;

-- 확인: 아래가 true 로 나오면 설정된 것입니다.
-- (site_is_admin 은 외부에서 호출할 수 없게 막혀 있지만, SQL Editor 는 소유자 권한이라 됩니다)
select site_is_admin('여기에_새_비밀번호') as 비밀번호_설정됨;
