-- ────────────────────────────────────────────────────────────
-- ① 비밀번호 대입 창구 차단
-- ────────────────────────────────────────────────────────────
-- 배경: site_is_admin 은 비밀번호의 참/거짓을 그대로 돌려준다.
--       외부에 열려 있으면 공개 키만으로 후보를 계속 던져 볼 수 있는
--       무제한 대입 창구가 된다. site_hash 도 같은 이유로 닫는다.
--
-- ★ 함정: `from public` 만으로는 닫히지 않는다.
--   Supabase 는 기본 권한 설정(ALTER DEFAULT PRIVILEGES)으로 public 스키마의
--   함수를 anon·authenticated 에게 '직접' 부여한다. 그래서 PUBLIC 상속분만
--   회수하면 직접 부여분이 그대로 남고, 점검하면 여전히 true 가 나온다.
--   실제로 이 함정에 한 번 걸렸고, ④의 점검 쿼리 덕분에 발견했다.
--
-- 기능에는 영향이 없다. 두 함수는 다른 함수 안에서만 불리고,
-- 그 함수들은 SECURITY DEFINER 라서 소유자 권한으로 돌기 때문이다.
revoke execute on function public.site_hash(text)     from public, anon, authenticated;
revoke execute on function public.site_is_admin(text) from public, anon, authenticated;


-- ────────────────────────────────────────────────────────────
-- ② 게임 랭킹 명부 삭제
-- ────────────────────────────────────────────────────────────
-- 배경: 게임 닉네임 입력 안내가 '닉/지역/성별/년' 형식을 권했고(예: 철수/논현/남/92),
--       그 값이 들어가는 테이블의 읽기 정책이 사실상 전면 허용이었다.
--       즉 공개 키만 있으면 이름·동네·성별·나이가 한 줄로 묶인
--       커뮤니티 명부를 통째로 내려받을 수 있는 상태였다.
--
-- 화면(HTML)을 지워도 데이터베이스 행은 사라지지 않으므로,
-- 게임 페이지 정리(안정화 이후 예정)와 별개로 지금 처리했다.
-- 테이블 자체 제거는 게임을 정리할 때 함께 한다.
do $$
declare t text;
begin
  foreach t in array array['game_players_v2','game_players','bakery_weekly'] loop
    if to_regclass('public.'||t) is not null then
      execute format('delete from public.%I', t);
      raise notice '비움: %', t;
    end if;
  end loop;
end $$;


-- ────────────────────────────────────────────────────────────
-- ③ 운영진 비밀번호 재설정
-- ────────────────────────────────────────────────────────────
-- ★★ 이 블록은 이미 적용됐다. 그대로 다시 실행하지 말 것. ★★
--    따옴표 안이 자리표시자라서, 이 상태로 실행하면 비밀번호가
--    누구나 아는 문자열로 되돌아간다.
--    비밀번호를 바꿀 때는 sql/set_admin_password.sql 을 쓴다.
--
-- 배경: 예전 설치 파일이 비밀번호를 'on conflict do update' 로 넣어서,
--       파일을 편집 없이 다시 Run 하면 공개 저장소에 적힌 CHANGE_ME 로
--       되돌아갔다. 그런데 파일 머리말은 '재실행해도 안전합니다'라고 안내했다.
--       그동안 되돌아간 적이 있었는지 알 수 없으므로 한 번 새로 설정했다.
--
--   insert into site_config (key, value)
--   values ('admin_pass_hash', site_hash('여기에_실제_비밀번호'))
--   on conflict (key) do update set value = excluded.value;


-- ────────────────────────────────────────────────────────────
-- ④ 점검 — 언제 돌려도 안전하다. 바꿀 것 없음.
-- ────────────────────────────────────────────────────────────
-- 셋 다 false 여야 정상이다.
--   판정함수_열림 / 해시함수_열림 : 외부에서 비밀번호를 떠볼 수 있는가
--   예시문구_통함               : 안내 문서의 자리표시자가 아직 비밀번호인가
select has_function_privilege('anon','public.site_is_admin(text)','execute') as 판정함수_열림,
       has_function_privilege('anon','public.site_hash(text)','execute')     as 해시함수_열림,
       site_is_admin('여기에_새_비밀번호')                                    as 예시문구_통함;


